/// Returns a PRIME import request if the frame is a two-plane NV12 DMA-BUF.
pub fn prime_nv12_descriptor(frame: &RawFrame) -> Option<PrimeNv12> {
    if frame.format != PixelFormat::Nv12 {
        return None;
    }
    let planes = frame.dma_buf.as_ref()?;
    if planes.len() != 2 || !planes.iter().all(DmaBufPlane::is_valid) {
        return None;
    }
    let (w, h) = (frame.width, frame.height);
    if w == 0 || h == 0 || !w.is_multiple_of(2) || !h.is_multiple_of(2) {
        return None;
    }
    Some(PrimeNv12 {
        width: w,
        height: h,
        planes: [prime_plane(&planes[0], h), prime_plane(&planes[1], h / 2)],
    })
}

/// Returns a single-plane RGB import request for a BGRA or RGBA DMA-BUF.
pub fn prime_rgb_descriptor(frame: &RawFrame) -> Option<PrimeRgb> {
    let fourcc = match frame.format {
        PixelFormat::Bgra8 => VA_FOURCC_BGRA,
        PixelFormat::Rgba8 => VA_FOURCC_RGBA,
        _ => return None,
    };
    let planes = frame.dma_buf.as_ref()?;
    if planes.len() != 1 || !planes[0].is_valid() || frame.width == 0 || frame.height == 0 {
        return None;
    }
    Some(PrimeRgb {
        width: frame.width,
        height: frame.height,
        fourcc,
        drm_format: if fourcc == VA_FOURCC_BGRA {
            DRM_FORMAT_ARGB8888
        } else {
            DRM_FORMAT_ABGR8888
        },
        plane: prime_plane(&planes[0], frame.height),
    })
}

fn prime_plane(p: &DmaBufPlane, rows: u32) -> PrimePlane {
    PrimePlane {
        fd: p.raw_fd(),
        size: p.offset.saturating_add(p.stride.saturating_mul(rows)),
        pitch: p.stride,
        offset: p.offset,
        modifier: p.modifier,
    }
}

/// Packs a frame into NV12 on the CPU using the configured colour matrix and range.
/// NV12 frames are copied unchanged; BGRA and RGBA frames are converted.
pub fn nv12_from_frame(frame: &RawFrame, colour: &ColourConfig) -> Result<Vec<u8>, VaError> {
    let (w, h) = (frame.width as usize, frame.height as usize);
    if w == 0 || h == 0 || !w.is_multiple_of(2) || !h.is_multiple_of(2) {
        return Err(VaError::Invalid(format!(
            "NV12 requires even non-zero dimensions, got {w}x{h}"
        )));
    }
    let stride = frame.stride as usize;
    if frame.data.is_empty() {
        return Err(VaError::Invalid(
            "frame has no CPU-readable data (DMA-BUF only); the VPP path could not convert it"
                .into(),
        ));
    }
    let data = &frame.data[..];
    match frame.format {
        PixelFormat::Nv12 => {
            if stride < w || data.len() < stride * h * 3 / 2 {
                return Err(VaError::Invalid("NV12 frame data is too small".into()));
            }
            let mut out = Vec::with_capacity(w * h * 3 / 2);
            for row in 0..h {
                out.extend_from_slice(&data[row * stride..row * stride + w]);
            }
            for row in 0..h / 2 {
                let start = stride * h + row * stride;
                out.extend_from_slice(&data[start..start + w]);
            }
            Ok(out)
        }
        PixelFormat::Bgra8 | PixelFormat::Rgba8 => {
            if stride < w * 4 || data.len() < stride * h {
                return Err(VaError::Invalid("RGB frame data is too small".into()));
            }
            let (ri, bi) = if frame.format == PixelFormat::Rgba8 {
                (0, 2)
            } else {
                (2, 0)
            };
            let conv = Rgb2Yuv::new(colour);
            let px = |x: usize, y: usize| -> (f32, f32, f32) {
                let o = y * stride + x * 4;
                (data[o + ri] as f32, data[o + 1] as f32, data[o + bi] as f32)
            };
            let mut out = vec![0u8; w * h * 3 / 2];
            for y in 0..h {
                for x in 0..w {
                    let (r, g, b) = px(x, y);
                    out[y * w + x] = conv.luma(r, g, b);
                }
            }
            let mut chroma = Vec::with_capacity(w * h / 2);
            for cy in 0..h / 2 {
                for cx in 0..w / 2 {
                    let (mut sr, mut sg, mut sb) = (0.0f32, 0.0f32, 0.0f32);
                    for dy in 0..2 {
                        for dx in 0..2 {
                            let (r, g, b) = px(cx * 2 + dx, cy * 2 + dy);
                            sr += r;
                            sg += g;
                            sb += b;
                        }
                    }
                    let (cb, cr) = conv.chroma(sr / 4.0, sg / 4.0, sb / 4.0);
                    chroma.push(cb);
                    chroma.push(cr);
                }
            }
            out[w * h..].copy_from_slice(&chroma);
            Ok(out)
        }
    }
}

/// RGB to Y'CbCr for one [`ColourConfig`]. Coefficients are from the matrix's kr and
/// kb; the range is limited (16-235 / 16-240) or full (0-255).
struct Rgb2Yuv {
    kr: f32,
    kb: f32,
    full: bool,
}

impl Rgb2Yuv {
    fn new(colour: &ColourConfig) -> Self {
        let (kr, kb) = colour.luma_coefficients();
        Self {
            kr,
            kb,
            full: colour.full_range,
        }
    }

    fn luma(&self, r: f32, g: f32, b: f32) -> u8 {
        let kg = 1.0 - self.kr - self.kb;
        let y = self.kr * r + kg * g + self.kb * b; // 0..255
        let v = if self.full {
            y
        } else {
            16.0 + y * 219.0 / 255.0
        };
        v.round().clamp(0.0, 255.0) as u8
    }

    fn chroma(&self, r: f32, g: f32, b: f32) -> (u8, u8) {
        let kg = 1.0 - self.kr - self.kb;
        let y = self.kr * r + kg * g + self.kb * b;
        let cb = (b - y) / (2.0 * (1.0 - self.kb));
        let cr = (r - y) / (2.0 * (1.0 - self.kr));
        let scale = if self.full { 1.0 } else { 224.0 / 255.0 };
        let to_u8 = |c: f32| (128.0 + c * scale).round().clamp(0.0, 255.0) as u8;
        (to_u8(cb), to_u8(cr))
    }
}

