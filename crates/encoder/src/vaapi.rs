/// Session objects created on the VA display.
#[derive(Default)]
struct Session {
    config: EncoderConfig,
    selection: Option<EncodeSelection>,
    config_id: Option<u32>,
    context: Option<u32>,
    coded: Option<u32>,
    recon: Vec<u32>,
    input: Vec<u32>,
    next_input: usize,
    dpb: Dpb,
    frame_counter: u64,
    idr_base: u64,
    /// Pictures successfully encoded since (and not including) the last IDR was
    /// started. Zero at an IDR, so H.264 `frame_num` is 0 there; it advances only
    /// after a picture was encoded, so a failed encode leaves no gap.
    coded_since_idr: u32,
    /// IDRs started so far; low 16 bits are `idr_pic_id` (consecutive IDRs differ).
    idr_count: u32,
    sequence_started: bool,
    cpu_fallback_logged: bool,
    /// Config and context for the RGB-to-NV12 VPP pass, created on first use.
    vpp: Option<(u32, u32)>,
    /// Rolling intra refresh: `Some(column)` when the session was configured for it.
    rolling_refresh: Option<bool>,
    /// Parameter sets supplied by this crate (HEVC VPS/SPS/PPS with VUI colour).
    packed: Vec<PackedHeader>,
}

impl Session {
    /// Destroys in dependency order: the coded buffer, then contexts (the VPP context
    /// renders into the input surfaces, so it goes before them), then configs, then
    /// the surfaces.
    fn destroy(&mut self, layer: &mut dyn VaLayer) {
        if let Some(c) = self.coded.take() {
            layer.destroy_buffer(c);
        }
        let vpp = self.vpp.take();
        if let Some((_, ctx)) = vpp {
            layer.destroy_context(ctx);
        }
        if let Some(ctx) = self.context.take() {
            layer.destroy_context(ctx);
        }
        if let Some((cfg, _)) = vpp {
            layer.destroy_config(cfg);
        }
        if let Some(cfg) = self.config_id.take() {
            layer.destroy_config(cfg);
        }
        let mut surfaces = std::mem::take(&mut self.recon);
        surfaces.append(&mut self.input);
        if !surfaces.is_empty() {
            layer.destroy_surfaces(&surfaces);
        }
        self.dpb.clear();
    }
}

/// Picture kind for a frame. Determines slice type, NAL type and output flags.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum PictureKind {
    /// IDR. Starts a sequence and resets the DPB.
    Idr,
    /// Non-IDR I-frame used as a recovery point when no valid reference remains.
    Recovery,
    /// Periodic full I-frame, used when the driver has no rolling intra refresh.
    IntraRefresh,
    /// P-frame referencing the newest valid DPB entry.
    Inter,
}

impl PictureKind {
    fn is_intra(self) -> bool {
        !matches!(self, PictureKind::Inter)
    }
    /// Value written to `EncodedFrame::picture_type` (informational).
    fn picture_type(self) -> u32 {
        match self {
            PictureKind::Idr => 3,
            PictureKind::Recovery => 2,
            PictureKind::IntraRefresh => 6,
            PictureKind::Inter => 0,
        }
    }
}

