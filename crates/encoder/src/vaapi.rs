fn codec_name(codec: VideoCodec) -> &'static str {
    match codec {
        VideoCodec::Av1 => "AV1",
        VideoCodec::Hevc => "HEVC",
        VideoCodec::H264 => "H.264",
    }
}

/// Profiles to try, in preference order.
fn candidate_profiles(codec: VideoCodec) -> &'static [c_int] {
    match codec {
        VideoCodec::Hevc => &[VA_PROFILE_HEVC_MAIN],
        VideoCodec::Av1 => &[VA_PROFILE_AV1_PROFILE0],
        VideoCodec::H264 => &[VA_PROFILE_H264_HIGH, VA_PROFILE_H264_MAIN],
    }
}

/// Entrypoints to try, in preference order. LP (VDEnc / low-power) comes first
/// because it is the low-latency path on Intel and VCN-based AMD hardware. AV1
/// is deliberately LP-only: this backend does not use the full-slice AV1 path.
fn preferred_entrypoints(codec: VideoCodec) -> &'static [c_int] {
    match codec {
        VideoCodec::Hevc | VideoCodec::H264 => {
            &[VA_ENTRYPOINT_ENC_SLICE_LP, VA_ENTRYPOINT_ENC_SLICE]
        }
        VideoCodec::Av1 => &[VA_ENTRYPOINT_ENC_SLICE_LP],
    }
}

/// Selects the profile and entrypoint for `codec` and checks that the driver
/// can do what this backend needs: 4:2:0 render targets and CBR rate control.
///
/// AV1 is refused unless `options.av1` is set, before the driver is even asked.
pub fn select_encode(
    layer: &mut dyn VaLayer,
    codec: VideoCodec,
    options: &VaapiOptions,
) -> Result<EncodeSelection, VaError> {
    if codec == VideoCodec::Av1 && !options.av1 {
        return Err(VaError::Unsupported(format!(
            "AV1 is disabled for VA-API (experimental, incomplete buffers); set {VAAPI_AV1_ENV}=1 to opt in"
        )));
    }
    let profiles = layer.query_profiles()?;
    let profile = candidate_profiles(codec)
        .iter()
        .copied()
        .find(|p| profiles.contains(p))
        .ok_or_else(|| {
            VaError::Unsupported(format!(
                "driver does not offer a {} encode profile; offers {profiles:?}",
                codec_name(codec)
            ))
        })?;
    let entrypoints = layer.query_entrypoints(profile)?;
    let entrypoint = preferred_entrypoints(codec)
        .iter()
        .copied()
        .find(|e| entrypoints.contains(e))
        .ok_or_else(|| {
            VaError::Unsupported(format!(
                "no usable encode entrypoint for {}: driver offers {entrypoints:?}",
                codec_name(codec)
            ))
        })?;
    let attribs = layer.query_attribs(
        profile,
        entrypoint,
        &[
            VA_CONFIG_ATTRIB_RT_FORMAT,
            VA_CONFIG_ATTRIB_RATE_CONTROL,
            VA_CONFIG_ATTRIB_ENC_PACKED_HEADERS,
            VA_CONFIG_ATTRIB_ENC_INTRA_REFRESH,
        ],
    )?;
    let get = |ty: c_int| {
        attribs
            .iter()
            .find(|a| a.attrib_type == ty)
            .map(|a| a.value)
            .filter(|v| *v != VA_ATTRIB_NOT_SUPPORTED)
    };
    let rt = get(VA_CONFIG_ATTRIB_RT_FORMAT).unwrap_or(0);
    if rt & VA_RT_FORMAT_YUV420 == 0 {
        return Err(VaError::Unsupported(
            "driver does not offer 4:2:0 render targets".into(),
        ));
    }
    let rc = get(VA_CONFIG_ATTRIB_RATE_CONTROL).unwrap_or(0);
    if rc & VA_RC_CBR == 0 {
        return Err(VaError::Unsupported(
            "driver does not offer constant-bitrate rate control".into(),
        ));
    }
    let vpp = layer
        .query_entrypoints(VA_PROFILE_NONE)
        .map(|eps| eps.contains(&VA_ENTRYPOINT_VIDEO_PROC))
        .unwrap_or(false);
    Ok(EncodeSelection {
        profile,
        entrypoint,
        packed_headers: get(VA_CONFIG_ATTRIB_ENC_PACKED_HEADERS)
            .unwrap_or(VA_ENC_PACKED_HEADER_NONE),
        intra_refresh: get(VA_CONFIG_ATTRIB_ENC_INTRA_REFRESH).unwrap_or(0)
            & (VA_ENC_INTRA_REFRESH_ROLLING_COLUMN | VA_ENC_INTRA_REFRESH_ROLLING_ROW),
        vpp,
    })
}

/// Probes a layer for `codec` and reports the vendor and the selected mode.
pub fn probe_with(
    layer: &mut dyn VaLayer,
    codec: VideoCodec,
    options: &VaapiOptions,
) -> Result<ProbeReport, VaError> {
    // Refuse a disabled codec before touching the driver.
    if codec == VideoCodec::Av1 && !options.av1 {
        return Err(VaError::Unsupported(format!(
            "AV1 is disabled for VA-API (experimental, incomplete buffers); set {VAAPI_AV1_ENV}=1 to opt in"
        )));
    }
    let vendor = layer.open()?;
    let selection = select_encode(layer, codec, options)?;
    Ok(ProbeReport { vendor, selection })
}

/// Probes the real libva installation for `codec`, with the options from the
/// environment. AV1 reports unsupported unless [`VAAPI_AV1_ENV`] is set.
pub fn probe(codec: VideoCodec) -> Result<ProbeReport, VaError> {
    let mut layer = LibVa::new();
    probe_with(&mut layer, codec, &VaapiOptions::from_env())
}

